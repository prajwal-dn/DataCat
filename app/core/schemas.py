"""Pydantic schemas for DATACAT Tier 2 telemetry and receipt validation.

Strictly rejects any unexpected extra fields.
"""
from datetime import datetime
from typing import Any
from pydantic import BaseModel, ConfigDict, Field, field_validator


class Metrics(BaseModel):
    """Operational metrics collected by Tier 1."""
    model_config = ConfigDict(extra="forbid")

    cpu_usage: float = Field(..., ge=0.0, le=100.0, description="CPU usage percentage")
    memory_usage: float = Field(..., ge=0.0, le=100.0, description="Memory usage percentage")
    disk_usage: float = Field(..., ge=0.0, le=100.0, description="Disk usage percentage")
    latency_ms: float = Field(..., ge=0.0, description="System/network latency in milliseconds")


class TelemetryEvent(BaseModel):
    """Operational telemetry event emitted by Tier 1."""
    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(..., min_length=1, description="Unique event identifier")
    tenant_id: str = Field(..., min_length=1, description="Tenant/organization identifier")
    server_id: str = Field(..., min_length=1, description="Monitored server identifier")
    timestamp_utc: str = Field(..., min_length=1, description="ISO 8601 UTC timestamp")
    metrics: Metrics = Field(..., description="Numerical telemetry metrics")
    policy_version: str = Field(..., min_length=1, description="Privacy policy version")

    @field_validator("timestamp_utc")
    @classmethod
    def validate_timestamp_utc(cls, v: str) -> str:
        try:
            # Parse ISO 8601 timestamp (supporting Z and offset notations)
            normalized = v.replace("Z", "+00:00")
            datetime.fromisoformat(normalized)
        except Exception as e:
            raise ValueError(f"Invalid ISO 8601 timestamp: '{v}'") from e
        return v


class SignedReceipt(BaseModel):
    """Cryptographic receipt generated by Tier 1 for telemetry verification."""
    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(..., min_length=1, description="Must match event.event_id")
    tenant_id: str = Field(..., min_length=1, description="Must match event.tenant_id")
    payload_hash: str = Field(
        ...,
        min_length=64,
        max_length=64,
        pattern=r"^[0-9a-fA-F]{64}$",
        description="SHA-256 payload hash in hexadecimal format",
    )
    collector_id: str = Field(..., min_length=1, description="Registered collector identifier")
    sequence_number: int = Field(..., ge=0, description="Collector sequence number")
    policy_version: str = Field(..., min_length=1, description="Must match event.policy_version")
    algorithm: str = Field(..., description="Must be Ed25519")
    signature: str = Field(..., min_length=1, description="Base64-encoded Ed25519 digital signature")

    @field_validator("algorithm")
    @classmethod
    def validate_algorithm(cls, v: str) -> str:
        if v.lower() != "ed25519":
            raise ValueError(f"Unsupported algorithm '{v}'. Only 'Ed25519' is accepted.")
        return v


class IngestionRequest(BaseModel):
    """Raw ingestion envelope containing event and cryptographic receipt."""
    model_config = ConfigDict(extra="forbid")

    event: dict[str, Any] = Field(..., description="Original raw event payload dictionary")
    receipt: dict[str, Any] = Field(..., description="Cryptographic receipt dictionary")
